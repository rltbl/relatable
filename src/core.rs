    /// Get the full schema:
    /// - all the tables in the "table" table
    /// - all of the columns in the "column" table
    /// - all of the datatypes from the "datatype" table
    pub async fn schema(&self) -> Result<Schema> {
        let sql = match self.pool.kind() {
            DbKind::SQLite => {
                r#"SELECT
                       main.name,
                       tbl.path
                   FROM sqlite_master AS main
                   LEFT JOIN "table" AS tbl ON main.name = tbl."table"
                   WHERE main.type = 'table'
                     AND main.name != 'sqlite_sequence';"#
            }
            DbKind::PostgreSQL => {
                r#"SELECT
                       main.table_name AS name,
                       tbl.path
                   FROM information_schema.tables AS main
                   LEFT JOIN "table" AS tbl ON main.table_name = tbl."table"
                   WHERE main.table_schema IN (
                       SELECT REGEXP_SPLIT_TO_TABLE("setting", ', ')
                       FROM "pg_settings"
                       WHERE "name" = 'search_path'
                   );"#
            }
        };
        let tables: Vec<Table> = self
            .pool
            .query(&sql, ())
            .await?
            .remove_nulls()
            .try_into_vec()?;
        let mut tables = tables
            .into_iter()
            .map(|table: Table| (table.name.clone(), table))
            .collect::<IndexMap<String, Table>>();

        let sql = match self.pool.kind() {
            DbKind::SQLite => "SELECT name FROM sqlite_master WHERE type = 'view'",
            DbKind::PostgreSQL => r#"SELECT table_name FROM information_schema.views;"#,
        };
        let views = self.pool.query(sql, ()).await?.to_strings()?;
        for table in tables.values_mut() {
            let view = format!("{}_default_view", table.name);
            if views.contains(&view) {
                table.view = view;
            }
        }

        let columns = self.column_table().get_all().await?;
        for column in columns.iter() {
            if let Some(table) = tables.get_mut(&column.table) {
                if column.is_meta() {
                    table.has_meta = true;
                }
            }
        }

        let datatypes = self.datatypes().await;

        Ok(Schema {
            tables,
            columns,
            datatypes,
        })
    }

    /// Check that a table exists in the database.
    pub async fn table_exists(&self, table_name: &str) -> Result<bool> {
        let sql = match self.pool.kind() {
            DbKind::SQLite => "SELECT name FROM sqlite_master WHERE name = $1",
            DbKind::PostgreSQL => {
                r#"SELECT table_name FROM information_schema.tables WHERE table_name = $1;"#
            }
        };
        // TODO: support Postgres
        let rows = self.pool.query(sql, [table_name]).await?;
        Ok(rows.len() > 0)
    }

    /// Drop the given table in the database
    pub async fn drop_table(&self, table_name: &str) -> Result<bool> {
        if self.table_exists(table_name).await? {
            self.delete_message(table_name, &[], None, None, None)
                .await?;
            // TODO: delete history and changes
            let sql = match self.pool.kind() {
                DbKind::SQLite => format!(r#"DROP TABLE "{table_name}""#),
                DbKind::PostgreSQL => {
                    format!(r#"DROP TABLE "{table_name}" CASCADE"#)
                }
            };
            self.pool.execute_batch(&sql).await?;
            Ok(true)
        } else {
            Ok(false)
        }
    }

    // Drop all of the tables in the table table
    pub async fn drop_data_tables(&self) -> Result<()> {
        tracing::trace!("Relatable::drop_data_tables({self:?})");
        if !Table::table_exists("table", self).await? {
            tracing::warn!("Can't get list of tables to drop: The table table does not exist");
        } else {
            // TODO: sort tables by dependency, drop in referse order
            let tables = self.get_tables().await?;
            for table in tables.keys() {
                self.drop_table(table).await?;
            }
        }
        Ok(())
    }

    // Drop all of the meta tables
    pub async fn drop_meta_tables(&self) -> Result<()> {
        tracing::trace!("Relatable::drop_meta_tables({self:?})");
        for table_name in [
            "cache", "history", "change", "user", "message", "datatype", "column", "table",
        ] {
            let mut table = Table {
                name: table_name.to_string(),
                ..Default::default()
            };
            table.drop_table(self).await?;
        }
        Ok(())
    }

    /// Drop all of the data tables and metatables in the database
    pub async fn drop_tables(&self) -> Result<()> {
        tracing::trace!("Relatable::drop_tables({self:?})");
        self.drop_data_tables().await?;
        self.drop_meta_tables().await?;
        Ok(())
    }

    /// Render this relatable instance in HTML according to the given template and context
    pub fn render<T: Serialize>(&self, template: &str, context: T) -> Result<String> {
        tracing::trace!("Relatable::render({template:?}, context)");
        // TODO: Optionally we should set up the environment once and store it,
        // but during development it's very convenient to rebuild every time.
        let mut env = Environment::new();

        // Load default template strings at compile time.
        let templates = IndexMap::from([
            ("page.html", include_str!("templates/page.html")),
            ("table.html", include_str!("templates/table.html")),
            ("row_menu.html", include_str!("templates/row_menu.html")),
            (
                "column_menu.html",
                include_str!("templates/column_menu.html"),
            ),
            ("cell_menu.html", include_str!("templates/cell_menu.html")),
        ]);

        // Load templates dynamically if src/templates/ exists,
        // otherwise use strings from compile time.
        // TODO: This should be a configuration option.
        let dir = std::env::var("RLTBL_TEMPLATES").unwrap_or("src/templates/".to_string());
        if FilePath::new(&dir).is_dir() {
            env.set_loader(path_loader(dir));
        };
        for (name, content) in templates {
            match env.get_template(name) {
                Ok(_) => (),
                Err(_) => env.add_template(name, content).unwrap(),
            }
        }

        env.get_template(template)?
            .render(context)
            .map_err(|e| e.into())
    }

    /// Use the given [Select] to fetch data from the database.
    pub async fn fetch(&self, select: &Select) -> Result<ResultSet> {
        let schema = self.schema().await?;

        let table_name = &select.table_name;
        let mut table = schema
            .tables
            .get(table_name)
            .ok_or(RelatableError::MissingError(format!(
                "Missing table {} {schema:?}",
                select.table_name
            )))?
            .clone();
        if select.view_name == format!("{}_default_view", table.name) || select.view_name == "" {
            table.set_view(self, "default").await?;
        } else if select.view_name == format!("{}_text_view", table.name) {
            table.set_view(self, "text").await?;
        } else {
            tracing::warn!(
                "Unsupported view name: '{}'. Falling back to default view",
                select.view_name
            );
            table.set_view(self, "default").await?;
        }
        let mut columns = schema
            .columns(table_name)
            .into_iter()
            .map(|(_, v)| v.clone())
            .filter(|col| col.is_data())
            .collect::<Vec<Column>>();

        // Fetch the data
        let (statement, parameters) = select.to_sql(&self.pool.kind())?;
        let params = parameters.clone();
        let db_rows = self.pool.query(&statement, params).await?;
        let count = db_rows.len();
        tracing::info!("Fetched {count} rows");

        // Filter out the table's columns that do not occur in the select:
        if select.select.len() > 0 {
            columns = columns
                .iter()
                .filter(|column| {
                    select.select.iter().any(|sel| match sel {
                        SelectField::Column {
                            table: select_table,
                            column: select_column,
                            ..
                        } => {
                            *select_column == column.column
                                && (select_table == "" || *select_table == table.name)
                        }
                        SelectField::Expression { alias, .. } => *alias == column.column,
                    })
                })
                .map(|c| c.clone())
                .collect();
        }

        // Maybe we also want the ancestors?
        let required_datatypes: HashSet<String> = columns
            .iter()
            .map(|col| [col.nulltype.clone(), col.datatype.clone()])
            .flatten()
            .collect();
        let datatypes = self.datatypes().await;
        let datatypes = datatypes
            .values()
            .filter(|dt| required_datatypes.contains(&dt.datatype))
            .cloned()
            .collect();

        // Return the data:
        let rows: Vec<Row> = db_rows
            .rows
            .into_iter()
            .map(|db_row| db_row.into())
            .collect();
        let total = self.count(&select).await?;
        Ok(ResultSet {
            select: select.clone(),
            statement,
            parameters,
            range: Range {
                count,
                total,
                start: (select.offset + 1) as u64,
                end: (select.offset + count) as u64,
            },
            table,
            columns,
            datatypes,
            rows,
        })
    }

    /// Use the given [Select] to fetch data from the database.
    pub async fn fetch_rows(&self, select: &Select) -> Result<Vec<JsonRow>> {
        tracing::trace!("Relatable::fetch_rows({select:?})");
        let (statement, params) = select.to_sql(&self.pool.kind())?;
        let rows = self.pool.query(&statement, params).await?.try_into_vec()?;
        Ok(rows)
    }

    /// Get the number of rows returned by this [Select] using the given caching strategy.
    pub async fn count(&self, select: &Select) -> Result<u64> {
        tracing::trace!("Relatable::count({select:?})");
        let (statement, params) = select.to_sql_count(&self.pool.kind())?;
        let count = self.pool.query(&statement, params).await?.try_into()?;
        Ok(count)
    }

    // TODO: Carefully review this function.
    /// Loads the given table from the given path. When `force` is set to true, deletes any
    /// existing table of the same name in the database first. When `validate` is set to true,
    /// Validates each row before loading it. Note that this function may panic.
    pub async fn load_table(&self, table_name: &str, path: &str, force: bool) {
        tracing::trace!("Relatable::load_table({table_name:?}, {path:?}, {force})");
        // Read the records from the given TSV file:
        let mut rdr = ReaderBuilder::new()
            .has_headers(false)
            .delimiter(b'\t')
            .from_reader(File::open(path).expect(&format!("Unable to open '{path}'")));
        let mut records = rdr.records();

        // Extract the headers from the first line of the file, which we will need for the CREATE
        // TABLE statement:
        let headers = {
            let headers = match records.next() {
                None => panic!("'{path}' is empty"),
                Some(record) => match record {
                    Err(err) => panic!("Error reading from '{path}': {err}"),
                    Ok(headers) => headers.iter().map(|s| s.to_string()).collect::<Vec<_>>(),
                },
            };
            for header in &headers {
                if header.trim().is_empty() {
                    panic!("One or more of the header fields is empty for table '{table_name}'");
                }
            }
            headers
        };

        let db_kind = self.pool.kind();

        // Add an entry corresponding to the table being loaded to the table table:
        if force {
            // Delete any messages associated with the table and then delete the table:
            self.delete_message(table_name, &[], None, None, None)
                .await
                .expect("Error deleting messages");

            let sql = format!(
                r#"DELETE FROM "table" WHERE "table" = {sql_param}"#,
                sql_param = SqlParam::new(&db_kind).next(),
            );
            self.pool
                .execute(&sql, [table_name])
                .await
                .expect("Error deleting from table table");
        }
        let sql = format!(
            r#"INSERT INTO "table" ("table", "path") VALUES ({sql_params})"#,
            sql_params = SqlParam::new(&db_kind).get_as_list(2)
        );
        self.pool
            .execute(&sql, [table_name, path])
            .await
            .expect("Error inserting to table table");
        tracing::debug!("Table {table_name} (path: {path}) added to table table");

        // Initialize a new table struct and collect its columns configuration:
        let table = Table {
            name: table_name.to_string(),
            ..Default::default()
        };
        let configured_columns: Vec<Column> = self
            .column_table()
            .get_configured(&[table_name])
            .await
            .expect("get columns for this table")
            .into();
        let table_columns = headers
            .iter()
            .map(|header| {
                match configured_columns
                    .iter()
                    .filter(|col| header == &col.column || header == &col.label)
                    .nth(0)
                {
                    Some(col) => col.clone(),
                    None => ColumnBuilder::new(table_name, header).build().unwrap(),
                }
            })
            .collect::<Vec<Column>>();
        let table_column_refs: Vec<&Column> = table_columns.iter().collect();

        // Generate the SQL statements needed to create the table and execute them:
        let datatypes = self.datatypes().await;
        for sql in sql::generate_table_ddl(&table, &table_column_refs, &datatypes, force, &db_kind)
            .expect("Error getting DDL")
        {
            self.pool
                .execute(&sql, ())
                .await
                .expect("Error creating table");
        }

        // Insert the data into the table:
        let schema = self.schema().await.expect("schema with new table");
        let mut columns = vec!["_id".to_string(), "_order".to_string()];
        columns.append(
            &mut headers
                .iter()
                .map(|k| format!(r#"{k}"#))
                .collect::<Vec<_>>(),
        );
        let columns_line = columns
            .iter()
            .map(|k| format!(r#""{k}""#))
            .collect::<Vec<_>>()
            .join(", ");
        let mut id: RowID = 1;
        let mut order: RowOrder = id as RowOrder * NEW_ORDER_MULTIPLIER;
        let sql_first_part = format!(r#"INSERT INTO "{table_name}" ({columns_line}) VALUES "#);
        let mut sql_value_parts = vec![];
        let mut sql_param_gen = SqlParam::new(&self.pool.kind());
        let mut param_values: Vec<DbValue> = Vec::new();
        let max_params = match db_kind {
            DbKind::SQLite => sql::MAX_PARAMS_SQLITE,
            DbKind::PostgreSQL => sql::MAX_PARAMS_POSTGRES,
        };
        while let Some(row) = records.next() {
            let row = row.expect("Error processing row");
            // We add 2 here because of _id and _order:
            if (param_values.len() + row.len() + 2) >= max_params {
                let sql = format!(
                    "{sql_first_part} {sql_value_part}",
                    sql_value_part = sql_value_parts.join(", ")
                );
                self.pool
                    .execute(&sql, param_values.clone())
                    .await
                    .expect("Error inserting to table");
                tracing::info!(
                    "{num_rows} rows loaded to table {table_name}",
                    num_rows = id - 1
                );
                param_values.clear();
                sql_value_parts.clear();
                sql_param_gen.reset()
            }

            let mut sql_params = vec![];
            param_values.push(id.into());
            sql_params.push(sql_param_gen.next());
            param_values.push(order.into());
            sql_params.push(sql_param_gen.next());
            let sql_params = {
                for (i, value) in row.iter().enumerate() {
                    let (column, nulltype) = {
                        // We add 2 here because of _id and _order:
                        let column = match columns.get(i + 2) {
                            Some(column) => column,
                            None => panic!("Unable to retrieve column {}", i + 2),
                        };
                        let nulltype = schema
                            .column(table_name, column)
                            .expect(&format!("Column '{column}' not found"))
                            .nulltype
                            .to_owned();
                        (column, nulltype)
                    };
                    if nulltype == "empty" && value == "" {
                        sql_params.push("NULL".to_string());
                    } else {
                        if nulltype != "" && nulltype != "empty" {
                            tracing::warn!("Nulltype '{nulltype}' not supported",);
                        }

                        let sql_type = schema
                            .column(table_name, column)
                            .expect(&format!("Column '{column}' not found"))
                            .sql_type
                            .clone();
                        let param_value = match self.pool.kind().parse(&sql_type, value) {
                            Ok(param_value) => param_value,
                            Err(_) => {
                                self.add_message(
                                    "rltbl",
                                    &table.name,
                                    id,
                                    column,
                                    &serde_json::Value::String(value.to_string()),
                                    "error",
                                    "parse",
                                    &format!("Could not parse {sql_type} from '{value}'"),
                                )
                                .await
                                .expect("Error adding message");
                                DbValue::Null
                            }
                        };
                        sql_params.push(sql_param_gen.next());
                        param_values.push(param_value);
                    };
                }
                sql_params.join(", ")
            };
            // Add two extra SQL_PARAM for _id and _order:
            sql_value_parts.push(format!("({sql_params})"));
            id += 1;
            order += NEW_ORDER_MULTIPLIER;
        }
        if param_values.len() > 0 {
            let sql = format!(
                "{sql_first_part} {sql_value_part}",
                sql_value_part = sql_value_parts.join(", ")
            );
            self.pool
                .execute(&sql, param_values)
                .await
                .expect(&format!("Error inserting to {table_name}"));
            tracing::info!(
                "{num_rows} rows loaded to table {table_name}",
                num_rows = id - 1
            );
        }

        if self.validation_level == ValidationLevel::Full {
            self.validate_table(&table_name)
                .await
                .expect("Error validating table");
            let dependent_tables = schema.dependent_tables(table_name);
            for table in &dependent_tables {
                tracing::debug!("Validating dependent table '{}'", table.name);
                self.validate_structure_for_table(&schema, table_name)
                    .await
                    .expect("Error validating table");
            }
        }

        self.commit_to_git().await.expect("Error committing to git");
    }

    async fn create_table(&self, schema: &Schema, table_name: &str) -> Result<()> {
        // Generate the SQL statements needed to create the table and execute them:
        let column_refs: Vec<&Column> = schema
            .columns(table_name)
            .values()
            .cloned()
            .filter(|c| !c.column.starts_with("_"))
            .collect();
        for sql in sql::generate_table_ddl(
            schema.table(table_name)?,
            &column_refs,
            &schema.datatypes,
            true,
            &self.pool.kind(),
        )? {
            self.pool.execute(&sql, ()).await?;
        }
        Ok(())
    }

    fn prepare_value(
        &self,
        sql_type: &str,
        value: &JsonValue,
    ) -> Result<DbValue, rltbl_db::core::DbError> {
        let result = match value {
            serde_json::Value::Null => Ok(DbValue::Null),
            _ => {
                let string = match value {
                    JsonValue::String(string) => string.to_string(),
                    JsonValue::Null => "NULL".to_string(),
                    _ => value.to_string(),
                };
                self.pool.kind().parse(sql_type, &string)
            }
        };
        // println!("convert_json {sql_type} {value:?}");
        result
    }

    /// Prepare this row for insertion into the database.
    /// Return the row and any messages to insert.
    pub fn prepare_row(
        &self,
        schema: &Schema,
        table_name: &str,
        row: &JsonRow,
    ) -> (DbRow, Vec<DbRow>) {
        let id = row
            .get("_id")
            .unwrap_or(&json!(0))
            .clone()
            .as_i64()
            .unwrap_or_default() as RowID;
        let mut messages = Vec::new();
        let mut db_row = DbRow::new();
        for (column_name, value) in row.iter() {
            let value = schema.nullify_value(table_name, column_name, value);
            let sql_type = schema
                .column(table_name, &column_name)
                .and_then(|c| Some(c.sql_type.as_str()))
                .unwrap_or("text");
            let value = match self.prepare_value(sql_type, &value) {
                Ok(value) => value,
                Err(_) => {
                    messages.push(
                        db_row! {
                            "added_by" => "rltbl",
                            "table" => table_name,
                            "row" => id,
                            "column" => column_name,
                            "value" => value,
                            "level" => "error",
                            "rule" =>
format!("sql_type:{sql_type}"), "message" =>                       format!("{column_name} must be of type {sql_type}"), }
                    );
                    DbValue::Null
                }
            };
            db_row.insert(column_name.to_owned(), value);
        }
        (db_row, messages)
    }

    /// Reload a table from a TSV file at a path.
    /// This requires dropping the table (to reset counters)
    /// and recreating it from the schema,
    /// then reading rows from the TSV.
    pub async fn reload_table(&self, table_name: &str, path: &str) -> Result<()> {
        let schema = self.schema().await?;

        self.drop_table(table_name).await?;
        self.create_table(&schema, table_name).await?;

        // Read the records from the given TSV file:
        let mut rdr = ReaderBuilder::new()
            .has_headers(true)
            .delimiter(b'\t')
            .from_reader(File::open(path).expect(&format!("Unable to open '{path}'")));

        let headers = rdr.headers()?.clone();
        let mut column_refs: Vec<&str> = headers.deserialize(None)?;
        column_refs.insert(0, "_order");

        let records = rdr.records();
        let rows: Vec<JsonRow> = records
            .into_iter()
            .enumerate()
            .map(|(i, record)| {
                let mut row: JsonRow = record?.deserialize(Some(&headers))?;
                let index = i as i64 + 1;
                row.insert("_order".to_string(), json!(index * NEW_ORDER_MULTIPLIER));
                Ok(row)
            })
            .collect::<Result<Vec<JsonRow>>>()?;
        let row_refs: Vec<&JsonRow> = rows.iter().collect();
        self.insert_rows(&schema, table_name, &column_refs, &row_refs)
            .await?;

        if self.validation_level == ValidationLevel::Full {
            self.validate_table(&table_name)
                .await
                .expect("Error validating table");
            let dependent_tables = schema.dependent_tables(table_name);
            for table in &dependent_tables {
                tracing::debug!("Validating dependent table '{}'", table.name);
                self.validate_structure_for_table(&schema, table_name)
                    .await
                    .expect("Error validating table");
            }
        }

        Ok(())
    }

    pub async fn insert_rows(
        &self,
        schema: &Schema,
        table_name: &str,
        columns: &[&str],
        rows: &[&JsonRow],
    ) -> Result<Vec<RowID>> {
        let rows_and_messages: Vec<(DbRow, Vec<DbRow>)> = rows
            .iter()
            .map(|row| self.prepare_row(schema, table_name, row))
            .collect();
        let new_rows: Vec<DbRow> = rows_and_messages
            .iter()
            .map(|(row, _)| row.clone())
            .collect();
        let result_rows = self
            .pool
            .insert_returning(table_name, columns, new_rows, &["_id"])
            .await?;
        let row_ids: Vec<RowID> = result_rows
            .rows
            .into_iter()
            .map(|row| row.get("_id").unwrap().as_i64().unwrap() as RowID)
            .collect();

        let messages: Vec<DbRow> = rows_and_messages
            .iter()
            .map(|(_, message)| message.clone())
            .flatten()
            .collect();
        self.pool
            .insert(
                "message",
                &[
                    "added_by", "table", "row", "column", "value", "level", "rule", "message",
                ],
                messages,
            )
            .await?;
        Ok(row_ids)
    }

    pub async fn truncate_table(&self, table_name: &str) -> Result<()> {
        self.delete_message(table_name, &[], None, None, None)
            .await?;
        let sql = match self.pool.kind() {
            DbKind::SQLite => format!(r#"DELETE FROM "{table_name}""#),
            DbKind::PostgreSQL => format!(r#"TRUNCATE TABLE "{table_name}""#),
        };
        self.pool.execute(&sql, ()).await?;
        Ok(())
    }

    /// Returns a [Table] corresponding to the given table name.
    pub async fn get_table(&self, table_name: &str) -> Result<Table> {
        // If the default view exists, set the table's view to it, otherwise leave it blank:
        let result = Table::view_exists(table_name, "default", self).await?;
        let view = {
            if result {
                format!("{table_name}_default_view")
            } else {
                String::from("")
            }
        };

        Ok(Table {
            name: table_name.to_string(),
            view,
            ..Default::default()
        })
    }

    /// Save all of the tables that have entries in the table table to the path indicated for each
    /// table there, unless `save_dir` has been given, in which case save them all there instead.
    pub async fn save_all(&self, save_dir: Option<&str>) -> Result<()> {
        let schema = self.schema().await?;
        let mut tables = schema.tables.clone();
        for table in tables.values_mut() {
            if table.path == "" {
                continue;
            }
            let table_name = table.name.to_string();
            table.set_view(self, "text").await?;

            let path = match save_dir {
                Some(save_dir) => format!("{save_dir}/{table_name}.tsv"),
                None => table.path.clone(),
            };
            let mut writer = WriterBuilder::new()
                .delimiter(b'\t')
                .quote_style(QuoteStyle::Never)
                .from_path(path)?;
            let header_row = schema
                .columns(&table_name)
                .values()
                .filter(|col| col.is_data())
                .map(|col| &col.column) // TODO: handle labels
                .collect::<Vec<&String>>();
            writer.write_record(header_row.clone())?;

            let sql = format!(
                r#"SELECT {columns} FROM "{table_name}_text_view" ORDER BY "_order""#,
                columns = header_row
                    .iter()
                    .map(|c| format!(r#""{c}""#))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
            let data_rows = self.pool.query(&sql, ()).await?;
            for data_row in data_rows.rows {
                let values = {
                    let mut str_values = vec![];
                    for (column, value) in data_row.iter() {
                        match value {
                            DbValue::Text(s) => str_values.push(s.to_string()),
                            DbValue::SmallInteger(n) => str_values.push(n.to_string()),
                            DbValue::Integer(n) => str_values.push(n.to_string()),
                            DbValue::BigInteger(n) => str_values.push(n.to_string()),
                            DbValue::Real(n) => str_values.push(n.to_string()),
                            DbValue::BigReal(n) => str_values.push(n.to_string()),
                            DbValue::Null => {
                                match schema
                                    .column(&table_name, column)
                                    .ok_or(RelatableError::InputError(format!(
                                        "Column '{column}' not found"
                                    )))?
                                    .nulltype
                                    .as_str()
                                {
                                    "" => {
                                        str_values.push("".to_string());
                                    }
                                    // Note that the behaviour for the 'empty' nulltype happens
                                    // to be the same as that for no nulltype, but in general
                                    // that won't be true for every nulltype.
                                    "empty" => {
                                        str_values.push("".to_string());
                                    }
                                    nulltype => {
                                        tracing::warn!("Unsupported nulltype: '{nulltype}'");
                                        str_values.push("".to_string());
                                    }
                                };
                            }
                            _ => {
                                return Err(RelatableError::DataError(format!(
                                    "Value {value} is not a string, number or NULL"
                                ))
                                .into());
                            }
                        }
                    }
                    str_values
                };
                writer.write_record(values)?;
            }
        }

        Ok(())
    }

    /// Save all of the tables and commit the changes to git.
    pub async fn commit_to_git(&self) -> Result<()> {
        tracing::trace!("Relatable::commit_to_git()");
        let author = match std::env::var("RLTBL_GIT_AUTHOR") {
            Err(err) => match err {
                std::env::VarError::NotPresent => {
                    tracing::debug!("Not committing to git because RLTBL_GIT_AUTHOR not defined");
                    return Ok(());
                }
                _ => {
                    return Err(RelatableError::InputError(format!(
                        "Could not read from the environment: {err}"
                    ))
                    .into())
                }
            },
            Ok(author) => author,
        };
        tracing::info!("Committing to git on behalf of RLTBL_GIT_AUTHOR: '{author}'");

        // Save all the tables:
        self.save_all(None).await?;

        // Get the git status:
        let status = git::get_status()?;
        if status.behind != 0 {
            return Err(RelatableError::GitError(
                "Refusing to commit to a local repository that is behind the remote".to_string(),
            )
            .into());
        }

        // Possibly only amend the last commit, if it is by the same author and performed
        // on the same day:
        let (last_commit_author, days_ago) = git::get_last_commit_info()?;
        let is_amendment = (last_commit_author == author) && (days_ago < 1);

        // Stage any modified table files that have a path in the table table:
        let sql = format!(
            r#"SELECT "path" FROM "table" WHERE "path" {is_not} NULL"#,
            is_not = sql::is_not_clause(&self.pool.kind()),
        );
        let paths = self.pool.query(&sql, ()).await?.to_strings()?;
        git::add(&paths)?;

        // Finally, commit to git:
        git::commit("commit by rltbl", &author, is_amendment)?;
        Ok(())
    }

    /// Get the details of the last change made by the user from the change table.
    async fn get_last_change_for_user(
        &self,
        user: &str,
        action: &ChangeAction,
    ) -> Result<Option<(RowID, ChangeSet)>> {
        let mut sql_param = SqlParam::new(&self.pool.kind());
        let sql = format!(
            r#"SELECT "change_id", "user", "table", "description", "content"
               FROM "change"
               WHERE "user" = {sql_param_1} AND "action" = {sql_param_2}
               ORDER BY "change_id" DESC LIMIT 1"#,
            sql_param_1 = sql_param.next(),
            sql_param_2 = sql_param.next(),
        );
        let params = [user, &format!("{action}")];
        let records: Vec<JsonRow> = self
            .pool
            .query(&sql, params)
            .await?
            .remove_nulls()
            .iter()
            .map(|db_row| db_row.clone().into())
            .collect();
        match records.len() {
            0 => Ok(None),
            _ => {
                let change_id = records[0]
                    .get("change_id")
                    .and_then(|v| v.as_i64())
                    .unwrap_or_default() as RowID;
                let user = records[0]
                    .get("user")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .to_owned();
                let table = records[0]
                    .get("table")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .to_owned();
                let description = records[0]
                    .get("description")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default()
                    .to_owned();
                let content = records[0]
                    .get("content")
                    .and_then(|v| v.as_str())
                    .unwrap_or_default();
                let changes: Vec<Change> = serde_json::from_str(&content)?;
                Ok(Some((
                    change_id,
                    ChangeSet {
                        action: *action,
                        table,
                        user,
                        description,
                        changes: changes,
                    },
                )))
            }
        }
    }

    /// Record the given [ChangeSet] to the change and history tables.
    pub async fn record_changeset(&self, changeset: &ChangeSet) -> Result<()> {
        let user = changeset.user.clone();
        let action = changeset.action.to_string();
        let table = changeset.table.clone();
        let description = changeset.description.clone();

        // Begin by getting the current last change_id for this user, which we may need to look
        // up previous values of the row's columns in the history table later:
        let old_change_id = match &changeset.action {
            ChangeAction::Undo => {
                let (change_id, _) = self
                    .get_last_change_for_user(&changeset.user, &ChangeAction::Do)
                    .await?
                    .ok_or(RelatableError::DataError(
                        "No action for user found".to_string(),
                    ))?;
                Some(change_id)
            }
            ChangeAction::Redo => {
                let (change_id, _) = self
                    .get_last_change_for_user(&changeset.user, &ChangeAction::Undo)
                    .await?
                    .ok_or(RelatableError::DataError(
                        "No undo for user found".to_string(),
                    ))?;
                Some(change_id)
            }
            ChangeAction::Do => None,
        };

        // Now write the current change, which will generate a new last change_id:
        let statement = format!(
            r#"INSERT INTO change("user", "action", "table", "description", "content")
               VALUES ({sql_params})
               RETURNING change_id"#,
            sql_params = SqlParam::new(&self.pool.kind()).get_as_list(5)
        );
        let content = to_value(&changeset.changes).unwrap_or_default();
        let params = params![user, action, &table, description, content.to_string()];
        let change_id: RowID = self.pool.query(&statement, params).await?.try_into()?;

        for change in &changeset.changes {
            match change {
                Change::Update {
                    row,
                    column,
                    before,
                    after,
                } => {
                    let sql = format!(
                        r#"INSERT INTO "history"
                           ("change_id", "table", "row", "before", "after")
                           VALUES ({sql_params})
                           RETURNING "history_id""#,
                        sql_params = SqlParam::new(&self.pool.kind()).get_as_list(5)
                    );
                    let before = json!({column: before}).to_string();
                    let after = json!({column: after}).to_string();
                    let params = params![change_id, &table, row, before, after];
                    self.pool.execute(&sql, params).await?;
                }
                Change::Add { row, after: _ } => {
                    // If the row has just been newly added, it will be found in the table,
                    // otherwise we will use the old_change_id to look for it in the history
                    // table:
                    let sql = format!(r#"SELECT * FROM "{table}" WHERE _id = $1"#);
                    let json_row: JsonRow = match self.pool.query(&sql, [*row]).await?.row() {
                        Ok(db_row) => db_row
                            .clone()
                            .into_iter()
                            .map(|(key, val)| (key, val.into()))
                            .collect(),
                        Err(_) => match old_change_id {
                            Some(change_id) => {
                                let sql = format!(
                                    r#"SELECT "before"
                                         FROM "history"
                                        WHERE "change_id" = {sql_param}"#,
                                    sql_param = SqlParam::new(&self.pool.kind()).next()
                                );
                                let before: String =
                                    self.pool.query(&sql, [change_id]).await?.try_into()?;
                                let before = match serde_json::from_str::<JsonValue>(&before) {
                                    Err(err) => return Err(err.into()),
                                    Ok(JsonValue::Object(o)) => o,
                                    Ok(_) => {
                                        return Err(RelatableError::InputError(
                                            "The content parameter is not an object".to_string(),
                                        )
                                        .into());
                                    }
                                };
                                before
                            }
                            None => {
                                return Err(RelatableError::DataError(format!(
                                    "Row {row} of 'history' table not found"
                                ))
                                .into())
                            }
                        },
                    };
                    let sql = format!(
                        r#"INSERT INTO "history"
                           ("change_id", "table", "row", "after")
                           VALUES ({sql_params})
                           RETURNING "history_id""#,
                        sql_params = SqlParam::new(&self.pool.kind()).get_as_list(4)
                    );
                    let json_row_str = json!(json_row).to_string();
                    let params = params![change_id, &table, *row, json_row_str];
                    self.pool.execute(&sql, params).await?;
                }
                Change::Move {
                    row,
                    from_after: _,
                    to_after: _,
                } => {
                    let sql = format!(
                        r#"INSERT INTO "history"
                           ("change_id", "table", "row")
                           VALUES ({sql_params})
                           RETURNING "history_id""#,
                        sql_params = SqlParam::new(&self.pool.kind()).get_as_list(3)
                    );
                    let params = params![change_id, &table, row];
                    self.pool.execute(&sql, params).await?;
                }
                Change::Delete { row, after: _ } => {
                    let sql = format!(r#"SELECT * FROM {table} WHERE _id = $1"#);
                    let db_rows = self.pool.query(&sql, [*row]).await?;
                    let json_row: JsonRow = db_rows
                        .row()?
                        .clone()
                        .into_iter()
                        .map(|(key, val)| (key, val.into()))
                        .collect();
                    let sql = format!(
                        r#"INSERT INTO "history"
                           ("change_id", "table", "row", "before")
                           VALUES ({sql_params})
                           RETURNING "history_id""#,
                        sql_params = SqlParam::new(&self.pool.kind()).get_as_list(4)
                    );
                    let json_row_str = json!(json_row).to_string();
                    let params = params![change_id, &table, *row, json_row_str];
                    self.pool.execute(&sql, params).await?;
                }
            };
        }

        Ok(())
    }

    /// Returns a vector of the names of the tables that have entries in the table table
    pub async fn list_tables(&self) -> Result<Vec<String>> {
        tracing::trace!("Relatable::list_tables({self:?})");
        let statement = format!(r#"SELECT "table" FROM "table" ORDER BY _order"#);
        let rows = self.pool.query(&statement, ()).await?.to_strings()?;
        Ok(rows)
    }

    /// Returns all of the tables that have entries in the table table as a map from table names
    /// to Table structs.
    pub async fn get_tables(&self) -> Result<IndexMap<String, Table>> {
        tracing::trace!("Relatable::get_tables({self:?})");
        let mut tables = IndexMap::new();
        let statement = format!(r#"SELECT "_id", "_order", "table", "path" FROM "table""#);

        let names = self.pool.query(&statement, ()).await?.to_strings()?;
        for name in names {
            if !name.trim().is_empty() {
                tables.insert(
                    name.to_string(),
                    Table {
                        name: name.to_string(),
                        ..Default::default()
                    },
                );
            }
        }
        Ok(tables)
    }

    /// Returns a [Site] corresponding to the given username.
    pub async fn get_site(&self, username: &str) -> Site {
        tracing::trace!("Relatable::get_site({username:?})");
        let mut users = self.user_table().map().await;
        let user = users.shift_remove(username).unwrap_or_default().into();
        Site {
            title: "RLTBL".to_string(),
            root: self.root.clone(),
            editable: !self.readonly,
            user,
            users,
            tables: self.list_tables().await.unwrap_or_default(),
        }
    }

    /// Updates the cursor field in the user table for the user associated with the given
    /// changeset.
    pub async fn prepare_user_cursor(&self, changeset: &ChangeSet) -> Result<()> {
        // Make sure the user is present in the user table
        let username = changeset.user.clone();
        self.user_table().get_or_insert(&username).await;

        // Update the user's cursor position.
        let mut cursor = changeset.to_cursor()?;
        match changeset.action {
            ChangeAction::Undo | ChangeAction::Redo => match changeset.changes.first() {
                Some(Change::Delete { row, after: _ }) => {
                    cursor.row = Table::get_previous_row_id(&changeset.table, *row, &self).await?;
                }
                _ => (),
            },
            ChangeAction::Do => (),
        };

        self.user_table().update_cursor(&username, &cursor).await
    }

