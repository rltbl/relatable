    #[derive(Clone, Debug)]
    enum Act {
        // user, table, after_id, row
        Add(String, String, RowID, JsonValue),
        // user, table, row_id
        Delete(String, String, RowID),
        // user, table, row_id, column, row
        Set(String, String, RowID, String, JsonValue),
        // user, table, row_id, after_id
        Move(String, String, RowID, RowID),
        // user
        Undo(String),
        // user
        Redo(String),
    }

    impl Act {
        fn add(user: &str, table: &str, row: RowID, value: JsonValue) -> Self {
            Self::Add(user.to_string(), table.to_string(), row, value)
        }
        fn delete(user: &str, table: &str, row: RowID) -> Self {
            Self::Delete(user.to_string(), table.to_string(), row)
        }
        fn set(user: &str, table: &str, row: RowID, column: &str, value: JsonValue) -> Self {
            Self::Set(
                user.to_string(),
                table.to_string(),
                row,
                column.to_string(),
                value,
            )
        }
        fn r#move(user: &str, table: &str, row: RowID, after_id: RowID) -> Self {
            Self::Move(user.to_string(), table.to_string(), row, after_id)
        }
        fn undo(user: &str) -> Self {
            Self::Undo(user.to_string())
        }
        fn redo(user: &str) -> Self {
            Self::Redo(user.to_string())
        }
        fn user(&self) -> String {
            let user = match self {
                Act::Add(user, _, _, _) => user,
                Act::Delete(user, _, _) => user,
                Act::Set(user, _, _, _, _) => user,
                Act::Move(user, _, _, _) => user,
                Act::Undo(user) => user,
                Act::Redo(user) => user,
            };
            user.to_string()
        }
    }

    async fn run(rltbl: &Relatable, actions: &[Act]) -> Result<()> {
        for action in actions {
            println!("{action:?}");
            match action {
                Act::Add(user, table, row, value) => {
                    rltbl
                        .add_row(
                            &user,
                            &table,
                            if *row < 1 { None } else { Some(*row) },
                            value.as_object().expect("valid JSON"),
                        )
                        .await
                        .expect("add row");
                }
                Act::Delete(user, table, row) => {
                    rltbl
                        .delete_row(&user, &table, *row)
                        .await
                        .expect("delete row");
                }
                Act::Set(user, table, row, column, value) => {
                    rltbl
                        .set_value(&user, &table, *row, &column, &value)
                        .await
                        .expect("set value");
                }
                Act::Move(user, table, before, after) => {
                    rltbl
                        .move_row(&user, &table, *before, *after)
                        .await
                        .expect("move row");
                }
                Act::Undo(user) => {
                    rltbl.undo(&user).await.expect("undo");
                }
                Act::Redo(user) => {
                    rltbl.redo(&user).await.expect("redo");
                }
            }
        }

        Ok(())
    }

    #[derive(Debug)]
    struct TestStep {
        act: Act,
        history: Option<Vec<String>>,
    }

    impl TestStep {
        fn new(act: Act) -> Self {
            Self { act, history: None }
        }
    }

    #[derive(Debug)]
    struct TestBuilder {
        name: String,
        drop: bool,
        user: String,
        table: String,
        penguin: usize,
        steps: Vec<TestStep>,
    }

    #[allow(dead_code)]
    impl TestBuilder {
        fn new(name: &str) -> Self {
            Self {
                name: name.to_string(),
                drop: true,
                user: "test".to_string(),
                table: String::new(),
                penguin: 0,
                steps: Vec::new(),
            }
        }

        fn drop(&mut self, drop: bool) -> &mut Self {
            self.drop = drop;
            self
        }

        fn penguin(&mut self, size: usize) -> &mut Self {
            self.table = "penguin".to_string();
            self.penguin = size;
            self
        }

        #[allow(dead_code)]
        fn user(&mut self, user: &str) -> &mut Self {
            self.user = user.to_string();
            self
        }

        #[allow(dead_code)]
        fn table(&mut self, table: &str) -> &mut Self {
            self.table = table.to_string();
            self
        }

        fn history(&mut self, lines: Vec<&str>) -> &mut Self {
            let lines = lines.iter().map(|s| s.to_string()).collect();
            self.steps.last_mut().unwrap().history = Some(lines);
            self
        }

        fn append(&mut self, row: JsonValue) -> &mut Self {
            let act = Act::add(&self.user, &self.table, -1, row);
            let step = TestStep::new(act);
            self.steps.push(step);
            self
        }

        fn delete(&mut self, row_id: RowID) -> &mut Self {
            let act = Act::delete(&self.user, &self.table, row_id);
            let step = TestStep::new(act);
            self.steps.push(step);
            self
        }

        fn set(&mut self, row_id: RowID, column: &str, value: JsonValue) -> &mut Self {
            let act = Act::set(&self.user, &self.table, row_id, column, value);
            let step = TestStep::new(act);
            self.steps.push(step);
            self
        }

        fn r#move(&mut self, before: RowID, after: RowID) -> &mut Self {
            let act = Act::r#move(&self.user, &self.table, before, after);
            let step = TestStep::new(act);
            self.steps.push(step);
            self
        }

        fn undo(&mut self) -> &mut Self {
            let act = Act::undo(&self.user);
            let step = TestStep::new(act);
            self.steps.push(step);
            self
        }

        fn redo(&mut self) -> &mut Self {
            let act = Act::redo(&self.user);
            let step = TestStep::new(act);
            self.steps.push(step);
            self
        }

        async fn run(&self) -> Result<()> {
            let rltbl = Relatable::test(&self.name, false).await?;

            if self.penguin > 0 {
                crate::demo::build_demo(&rltbl, &true, self.penguin).await?;
            }

            let mut select = Select::from(&self.table);
            select.view_name = format!("{}_text", &self.table);
            let before = rltbl.fetch(&select).await.unwrap_or_default();

            for step in &self.steps {
                let actions: Vec<Act> = vec![step.act.clone()];
                run(&rltbl, &actions).await?;
                if let Some(expected) = &step.history {
                    let actual = rltbl.get_user_history_strings(&self.user, 100).await?;
                    assert_eq!(expected, &actual, "compare histories");
                }
            }

            let after = rltbl.fetch(&select).await?;

            // TODO: better to compare result sets
            assert_eq!(
                before.to_tsv(),
                after.to_tsv(),
                "compare TSV before and after"
            );

            if self.drop {
                rltbl.drop_test().await?;
            }
            Ok(())
        }
    }

