    /// Set one cell value.
    pub async fn set_value(
        &self,
        user: &str,
        table_name: &str,
        row_id: RowID,
        column_name: &str,
        value: &JsonValue,
    ) -> Result<History> {
        let schema = self.schema().await?;
        if !schema.tables.contains_key(table_name) {
            return Err(RelatableError::DataError(format!("No such table: {table_name}")).into());
        }
        let table = self.get_table(table_name).await?;
        let column = match schema.column(table_name, column_name) {
            Some(column) => column,
            None => {
                return Err(
                    RelatableError::DataError(format!("No such column: {column_name}")).into(),
                )
            }
        };
        let old_row = match table.get_row(row_id).await {
            Ok(row) => row,
            Err(_) => {
                return Err(RelatableError::DataError(format!("No such row: {row_id}")).into())
            }
        };
        let previous = [(
            row_id,
            column.id,
            old_row.get(column_name).unwrap_or(DbValue::Null),
        )];

        let new_value: DbValue = value.into_db_value();

        let user_row = user_row! { column_name => new_value.clone() };
        let pairs = [(row_id, user_row)];

        // If we're changing the name of a table, drop views first.
        if table_name == "table" && column_name == "table" {
            table.drop_views().await?;
        }

        table.update(&pairs).await?;

        let inner_row = indexmap! {
            "_id".to_string() => row_id.into(),
            format!("c{}", column.id) => new_value,
        };
        let inner_rows = vec![inner_row];
        let change = NewChange::UpdateRows {
            table_id: table.id,
            rows: inner_rows,
        };
        let history = History {
            history_id: 0,
            user: user.to_string(),
            // date,
            action: ChangeAction::Do,
            target: None,
            changes: vec![change],
        };
        let history = self.record(history).await?;
        self.previous_value_table()
            .extend(history.history_id, table.id, &previous)
            .await?;

        // TODO: also undo/redo these changes
        match table.name.as_str() {
            "table" => {
                if column_name == "table" {
                    // TODO: rename in the column table
                    table.create_views().await?;
                }
            }
            "column" => {
                let row = self.column_table().await?.get_row(row_id).await?;
                if let Some(table_name) = row.get("table").and_then(|v| Some(v.to_string())) {
                    if let Ok(target) = self.get_table(&table_name).await {
                        target.drop_views().await?;
                        target.create_views().await?;
                    }
                }
            }
            _ => (),
        }

        self.delete_message(table_name, &[&row_id], Some(column_name), None, None)
            .await?;

        // Optionally do full validation on the newly updated cell and add further
        // messages to the message table:
        if self.validation_level == ValidationLevel::Full {
            tracing::debug!("validating {table_name} {column_name} {row_id}");
            self._validate_column_optionally_for_row(&schema, &column, &[&row_id])
                .await?;
            for dep_column in schema.columns.dependents(column) {
                self._validate_structure_for_column_and_optionally_for_row(dep_column, &[])
                    .await?;
            }
        }

        Ok(history)
    }

    pub async fn set_values(&self, changeset: &ChangeSet) -> Result<ChangeSet> {
        let changeset = changeset.clone();
        let table_name = changeset.table.as_str();
        let schema = self.schema().await?;
        if !schema.tables.contains_key(table_name) {
            return Err(RelatableError::DataError(format!("No such table: {table_name}")).into());
        }
        let table = self.get_table(table_name).await?;
        let mut pairs: BTreeMap<RowID, UserRow> = BTreeMap::new();
        for change in &changeset.changes {
            match change {
                Change::Update {
                    row, column, after, ..
                } => {
                    pairs
                        .entry(*row)
                        .or_insert(UserRow::default())
                        .insert(column.to_string(), after.into());
                }
                _ => {
                    return Err(RelatableError::UserError(format!(
                        "Invalid change in set_values: {change:?}"
                    ))
                    .into())
                }
            }
        }
        let pairs: Vec<(RowID, UserRow)> = pairs.into_iter().collect();
        table.update(&pairs).await?;
        self.prepare_user_cursor(&changeset).await?;
        self.record_changeset(&changeset).await?;
        if changeset.changes.len() > 0 {
            self.commit_to_git().await?;
        }
        Ok(changeset)
    }

    /// Add a message to the message table.
    pub async fn add_message(
        &self,
        user: &str,
        table_name: &str,
        row: RowID,
        column: &str,
        value: &JsonValue,
        level: &str,
        rule: &str,
        message: &str,
    ) -> Result<(RowID, CellMessage)> {
        let sql = format!(
            r#"INSERT INTO "message"
               ("added_by", "table", "row", "column", "value",
                "level", "rule", "message")
               VALUES
               ({sql_params})
               RETURNING "message_id""#,
            sql_params = SqlParam::new(&self.pool.kind().name()).get_as_list(8)
        );
        let params = params![
            user,
            table_name,
            row,
            column,
            value.clone(),
            level,
            rule,
            message
        ];
        let message_id: RowID = self.pool.query(&sql, params).await?.try_into()?;

        Ok((
            message_id,
            CellMessage {
                value: value.clone(),
                level: level.to_string(),
                rule: rule.to_string(),
                message: message.to_string(),
            },
        ))
    }

    /// Add a row to the given table
    pub async fn add_row(
        &self,
        user: &str,
        table: &str,
        after_id: Option<RowID>,
        row: &JsonRow,
    ) -> Result<History> {
        let rows = vec![row];
        let after = after_id.unwrap_or(-1);
        self.insert_rows(user, table, after, &rows).await
    }

    // If after_id < 0 then append.
    pub async fn insert_rows(
        &self,
        user: &str,
        table_name: &str,
        after_id: RowID,
        rows: &[&JsonRow],
    ) -> Result<History> {
        let table = self.get_table(table_name).await?;
        let mut user_rows = Vec::new();
        for row in rows {
            let db_row: DbRow = row.into_db_row();
            let user_row: UserRow = db_row.into();
            user_rows.push(user_row);
        }
        let user_rows = UserRows { rows: user_rows };
        let change = self.inner_insert_rows(&table, after_id, user_rows).await?;
        let history = History {
            history_id: 0,
            user: user.to_string(),
            // date,
            action: ChangeAction::Do,
            target: None,
            changes: vec![change.clone()],
        };
        let history = self.record(history).await?;

        // Optionally do full validation on the newly updated cell and add further
        // messages to the message table:
        if self.validation_level == ValidationLevel::Full {
            let row_ids: Vec<RowID> = match change {
                NewChange::InsertRows { rows, .. } => rows
                    .iter()
                    .filter_map(|row| row.get("_id").and_then(|i| i.as_i32()))
                    .collect(),
                _ => unreachable!(),
            };
            let refs: Vec<&RowID> = row_ids.iter().collect();
            self.validate_rows(&table_name, &refs).await?;
            let schema = self.schema().await?;
            for table in schema.dependent_tables(table_name) {
                self.validate_structure_for_table(&schema, &table.name)
                    .await?;
            }
        }

        Ok(history)
    }

    // Insert rows without considering the user or history.
    // Trigger creation of tables and views.
    async fn inner_insert_rows<'a>(
        &self,
        table: &DataTable<'a>,
        after: RowID,
        rows: UserRows,
    ) -> Result<NewChange> {
        let rows = if after < 0 {
            table.append(rows).await?
        } else {
            table.insert(after, rows).await?
        };
        match table.name.as_str() {
            "table" => {
                for row in rows.rows.iter() {
                    self.get_table_by_id(row.id).await?.create().await?;
                }
            }
            "column" => {
                let schema = self.schema().await?;
                let row_ids: Vec<RowID> = rows.rows.iter().map(|row| row.id).collect();
                let mut table_columns: IndexMap<String, Vec<&Column>> = IndexMap::new();
                for column in schema.columns.iter() {
                    if row_ids.contains(&column.id) {
                        table_columns
                            .entry(column.table.to_string())
                            .or_insert(Vec::new())
                            .push(column);
                    }
                }
                for (table_name, columns) in table_columns {
                    self.get_table(&table_name)
                        .await?
                        .add_columns(&columns)
                        .await?;
                }
            }
            _ => (),
        }
        let rows = rows.inner();
        Ok(NewChange::InsertRows {
            table_id: table.id,
            after_id: after,
            rows,
        })
    }

    async fn inner_delete_rows(&self, table_id: TableID, row_ids: &[RowID]) -> Result<()> {
        let table = self.get_table_by_id(table_id).await?;
        match table.name.as_str() {
            "table" => {
                for row_id in row_ids {
                    self.get_table_by_id(*row_id).await?.drop_views().await?;
                }
            }
            _ => (),
        };
        table.delete(row_ids).await?;
        Ok(())
    }

    async fn inner_undelete_rows(&self, table_id: TableID, row_ids: &[RowID]) -> Result<()> {
        let table = self.get_table_by_id(table_id).await?;
        table.undelete(row_ids).await?;
        match table.name.as_str() {
            "table" => {
                for row_id in row_ids {
                    self.get_table_by_id(*row_id).await?.create_views().await?;
                }
            }
            _ => (),
        };
        Ok(())
    }

    pub async fn delete_row(&self, user: &str, table_name: &str, row_id: RowID) -> Result<History> {
        let row_ids = vec![row_id];
        self.delete_rows(table_name, user, &row_ids).await
    }

    /// Delete a row from a given table
    pub async fn delete_rows(
        &self,
        table_name: &str,
        user: &str,
        row_ids: &[RowID],
    ) -> Result<History> {
        let schema = self.schema().await?;
        let table = match schema.tables.get(table_name) {
            Some(table) => table,
            None => {
                return Err(
                    RelatableError::DataError(format!("No such table: {table_name}")).into(),
                )
            }
        };
        let change = match table_name {
            "table" => {
                self.inner_delete_rows(table.id, row_ids).await?;
                let mut column_ids = Vec::new();
                for table in schema.tables.values() {
                    if row_ids.contains(&table.id) {
                        for column in schema.columns(&table.name).values() {
                            column_ids.push(column.id);
                        }
                    }
                }
                self.column_table().await?.delete(&column_ids).await?;
                NewChange::DeleteTables {
                    table_ids: Vec::from(row_ids),
                    column_ids,
                }
            }
            _ => {
                self.inner_delete_rows(table.id, row_ids).await?;
                NewChange::DeleteRows {
                    table_id: table.id,
                    row_ids: Vec::from(row_ids),
                }
            }
        };
        let history = History {
            history_id: 0,
            user: user.to_string(),
            // date,
            action: ChangeAction::Do,
            target: None,
            changes: vec![change],
        };
        self.record(history).await
    }

    /// Delete messages from the message table. Returns the number of messages deleted.
    pub async fn delete_message(
        &self,
        table: &str,
        rows: &[&RowID],
        column: Option<&str>,
        target_rule: Option<&str>,
        target_user: Option<&str>,
    ) -> Result<usize> {
        tracing::trace!(
            "Relatable::delete_message({self:?}, {table:?}, {rows:?}, {column:?}, \
             {target_rule:?}, {target_user:?})"
        );
        let mut sql_param = SqlParam::new(&self.pool.kind().name());
        let mut sql = format!(
            r#"DELETE FROM "message" WHERE "table" = {sql_param}"#,
            sql_param = sql_param.next()
        );
        let mut params: Vec<DbValue> = vec![table.into()];

        if rows.len() > 0 {
            sql.push_str(&format!(
                r#" AND "row" IN({sql_params})"#,
                sql_params = sql_param.get_as_list(rows.len()),
            ));
            params.extend(rows.iter().map(|row| DbValue::from(**row)));
        }
        if let Some(column) = column {
            sql.push_str(&format!(
                r#" AND "column" = {sql_param}"#,
                sql_param = sql_param.next()
            ));
            params.push(column.into());
        }
        if let Some(target_rule) = target_rule {
            sql.push_str(&format!(
                r#" AND "rule" LIKE {sql_param}"#,
                sql_param = sql_param.next()
            ));
            params.push(target_rule.into());
        }
        if let Some(target_user) = target_user {
            sql.push_str(&format!(
                r#" AND "added_by" = {sql_param}"#,
                sql_param = sql_param.next()
            ));
            params.push(target_user.into());
        }

        sql.push_str(r#" RETURNING 1 AS "deleted""#);
        let num_deleted = self.pool.query(&sql, params).await?.len();
        Ok(num_deleted)
    }

